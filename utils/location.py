def detect_location(text):
    """
    从文本中智能识别项目地域信息
    返回: (city, province, sea_area) 或 (None, None, None)
    """
    if not text:
        return None, None, None
    
    text = str(text)
    
    # 按关键词长度从长到短排序，优先匹配更具体的地名
    sorted_keys = sorted(LOCATION_DICT.keys(), key=lambda x: len(x), reverse=True)
    
    for key in sorted_keys:
        if key in text:
            city, province, sea_area = LOCATION_DICT[key]
            return city, province, sea_area
    
    return None, None, None


def sea_area_similarity(sea1, sea2):
    """
    计算两个海域的相似度
    返回 0-1 之间的分数
    """
    if not sea1 or not sea2:
        return 0.0
    
    if sea1 == sea2:
        return 1.0
    
    relations = SEA_AREA_RELATIONS.get(sea1, {})
    return relations.get(sea2, 0.2)


